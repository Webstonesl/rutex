class Slice:
    def __init__(self, start: int, end: Optional[int] = None):
        self.start = start
        self.end = end if end != None else self.start + 1

    def __repr__(self):
        if self.start + 1 == self.end:
            return str(self.start)
        return "%s..%s" % (self.start, self.end)

    def incEnd(self):
        self.end += 1


