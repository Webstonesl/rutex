impl From<u16> for LanguageCode {
    fn from(value: u16) -> Self {
        match value {
            0..95 | 128..150 => unsafe {
                // Safety: types are the same sizes and are checked for validity
                transmute::<u16, LanguageCode>(value)
            },
            _ => Self::Unknown,
        }
    }
}
