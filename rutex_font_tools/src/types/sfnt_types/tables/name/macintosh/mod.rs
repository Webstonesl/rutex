impl TryFrom<u16> for ScriptCode {
    type Error = SFNTError;

    fn try_from(value: u16) -> Result<Self, Self::Error> {
        Ok(match value {
            0 => ScriptCode::Roman,
            1 => ScriptCode::Japanese,
            2 => ScriptCode::TraditionalChinese,
            3 => ScriptCode::Korean,
            4 => ScriptCode::Arabic,
            5 => ScriptCode::Hebrew,
            6 => ScriptCode::Greek,
            7 => ScriptCode::Russian,
            8 => ScriptCode::RSymbol,
            9 => ScriptCode::Devanagari,
            10 => ScriptCode::Gurmukhi,
            11 => ScriptCode::Gujarati,
            12 => ScriptCode::Oriya,
            13 => ScriptCode::Bengali,
            14 => ScriptCode::Tamil,
            15 => ScriptCode::Telugu,
            16 => ScriptCode::Kannada,
            17 => ScriptCode::Malayalam,
            18 => ScriptCode::Sinhalese,
            19 => ScriptCode::Burmese,
            20 => ScriptCode::Khmer,
            21 => ScriptCode::Thai,
            22 => ScriptCode::Laotian,
            23 => ScriptCode::Georgian,
            24 => ScriptCode::Armenian,
            25 => ScriptCode::SimplifiedChinese,
            26 => ScriptCode::Tibetan,
            27 => ScriptCode::Mongolian,
            28 => ScriptCode::Geez,
            29 => ScriptCode::Slavic,
            30 => ScriptCode::Vietnamese,
            31 => ScriptCode::Sindhi,
            32 => ScriptCode::Roman,
            a => return Err(SFNTError::InvalidPlatformSpecificNumber("Macintosh", a)),
        })
    }
}
